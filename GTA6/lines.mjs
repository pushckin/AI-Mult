// Плоский список озвучиваемых реплик (для tts.mjs). Толпа озвучивается 5 голосами.
export function voicedLines() {
  const out = [];
  for (const part of Object.values(PARTS)) {
    for (const l of part.lines) {
      if (!l.who) continue;
      const clean = l.text.replace(/[{}]/g, '');
      if (l.who === 'crowd') {
        for (let i = 1; i <= 5; i++) out.push({ id: `${l.id}_c${i}`, voice: VOICES[`crowd${i}`], style: l.style, text: clean });
      } else {
        out.push({ id: l.id, voice: VOICES[l.who], style: l.style, text: clean });
      }
    }
  }
  return out;
}
